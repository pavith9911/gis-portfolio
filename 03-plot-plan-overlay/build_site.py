#!/usr/bin/env python3
"""
build_site.py - generates the SAMPLE housing-estate layout used by the viewer.

The estate ("Green Valley Estate"), its roads, plots and prices are invented. The script builds the
layout in local metres, rotates it, converts it to WGS84 around an arbitrary location and writes:
  data/plots.js      window.SITE = { plots, roads, boundary, ... } (GeoJSON features)
  data/site_plan.svg a georeferenced site-plan image used as an image overlay

To use real data: replace the plot polygons with your surveyed lot boundaries (e.g. exported from
QGIS as GeoJSON) and keep the same property names.
"""
import json
import math
import random
from pathlib import Path

HERE = Path(__file__).resolve().parent
random.seed(11)

LAT0, LON0 = 7.2600, 80.5800        # arbitrary sample location
ROT = math.radians(-15)             # layout rotation
PERCH = 25.2929                     # 1 perch = 25.2929 m2 (Sri Lankan land unit)
M_LAT = 111320.0
M_LON = 111320.0 * math.cos(math.radians(LAT0))


def to_lonlat(x, y):
    xr = x * math.cos(ROT) - y * math.sin(ROT)
    yr = x * math.sin(ROT) + y * math.cos(ROT)
    return [round(LON0 + xr / M_LON, 6), round(LAT0 + yr / M_LAT, 6)]


def rect(x0, y0, x1, y1):
    return [[x0, y0], [x1, y0], [x1, y1], [x0, y1], [x0, y0]]


def poly_feature(ring_xy, props):
    return {"type": "Feature", "properties": props,
            "geometry": {"type": "Polygon", "coordinates": [[to_lonlat(x, y) for x, y in ring_xy]]}}


def main():
    plots_xy = []   # (ring, facing, corner, frontage)
    W, D = 16, 36
    for i in range(12):                                   # north row
        x0 = -172 + i * W
        plots_xy.append((rect(x0, 4, x0 + W, 4 + D), "South", i in (0, 11), W))
    for i in range(12):                                   # south row
        x0 = -172 + i * W
        plots_xy.append((rect(x0, -4 - D, x0 + W, -4), "North", i in (0, 11), W))
    for j in range(8):                                    # east side of the cross road
        y0 = -96 + j * 24
        plots_xy.append((rect(36, y0, 36 + D, y0 + 24), "West", j in (0, 7), 24))

    statuses = ["Available"] * 18 + ["Reserved"] * 7 + ["Sold"] * 7
    random.shuffle(statuses)
    feats = []
    for n, ((ring, facing, corner, frontage), status) in enumerate(zip(plots_xy, statuses), start=1):
        xs = [p[0] for p in ring]
        ys = [p[1] for p in ring]
        area = (max(xs) - min(xs)) * (max(ys) - min(ys))
        perches = round(area / PERCH, 1)
        ppp = int(random.choice([650, 700, 725, 750, 800, 850]) * 1000 * (1.08 if corner else 1.0))
        ppp = round(ppp, -3)
        feats.append(poly_feature(ring, {
            "id": n, "no": f"P-{n:02d}", "area_m2": round(area), "perches": perches, "ppp": ppp,
            "price": int(round(ppp * perches, -4)), "status": status, "facing": facing,
            "corner": bool(corner), "frontage_m": frontage}))

    roads = [
        ("Main Road", rect(-176, -4, 28, 4)),
        ("Cross Road", rect(28, -104, 36, 104)),
    ]
    road_feats = [poly_feature(r, {"name": n}) for n, r in roads]
    boundary = poly_feature(rect(-180, -108, 76, 108), {"name": "Green Valley Estate (sample)"})
    park = poly_feature(rect(-172, -96, -112, -50), {"name": "Playground and green space"})

    # bounds of everything + margin
    allpts = [c for f in feats + road_feats + [boundary] for c in f["geometry"]["coordinates"][0]]
    west, east = min(p[0] for p in allpts), max(p[0] for p in allpts)
    south, north = min(p[1] for p in allpts), max(p[1] for p in allpts)
    mx, my = (east - west) * 0.04, (north - south) * 0.04
    west, east, south, north = west - mx, east + mx, south - my, north + my

    site = {
        "name": "Green Valley Estate", "note": "Sample layout with invented plots and prices",
        "center": [round((south + north) / 2, 6), round((west + east) / 2, 6)],
        "bounds": [[round(south, 6), round(west, 6)], [round(north, 6), round(east, 6)]],
        "perch_m2": PERCH,
        "plots": {"type": "FeatureCollection", "features": feats},
        "roads": {"type": "FeatureCollection", "features": road_feats},
        "boundary": boundary, "park": park,
    }
    (HERE / "data").mkdir(exist_ok=True)
    (HERE / "data" / "plots.js").write_text(
        "// Generated by build_site.py. Sample data: invented estate, plots and prices.\nwindow.SITE = "
        + json.dumps(site, separators=(",", ":")) + ";\n", encoding="utf-8")

    # ---- georeferenced SVG site plan (same bounds as above) ----
    wpx = 1400
    hpx = round(wpx * ((north - south) * M_LAT) / ((east - west) * M_LON))

    def px(lon, lat):
        return (lon - west) / (east - west) * wpx, (north - lat) / (north - south) * hpx

    def path(f, cls):
        pts = " ".join("%.1f,%.1f" % px(*c) for c in f["geometry"]["coordinates"][0])
        return f'<polygon class="{cls}" points="{pts}"/>'

    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {wpx} {hpx}" width="{wpx}" height="{hpx}">',
             '<style>.site{fill:#f4efde;stroke:#7a6f4d;stroke-width:3;stroke-dasharray:14 8}'
             '.road{fill:#cfc8b5;stroke:#8b8366;stroke-width:1.5}.plot{fill:#fffdf5;stroke:#3b3a30;stroke-width:1.6}'
             '.park{fill:#b5d99c;stroke:#4f7a3a;stroke-width:1.5}'
             'text{font-family:Georgia,serif;fill:#2b2a22;text-anchor:middle}.pn{font-size:15px;font-weight:700}'
             '.pp{font-size:11px}.rn{font-size:15px;letter-spacing:6px;fill:#6b6450}</style>',
             path(boundary, "site")]
    parts += [path(f, "road") for f in road_feats]
    parts.append(path(park, "park"))
    for f in feats:
        parts.append(path(f, "plot"))
        ring = f["geometry"]["coordinates"][0][:4]
        cx = sum(c[0] for c in ring) / 4
        cy = sum(c[1] for c in ring) / 4
        x, y = px(cx, cy)
        parts.append(f'<text class="pn" x="{x:.1f}" y="{y - 2:.1f}">{f["properties"]["no"]}</text>'
                     f'<text class="pp" x="{x:.1f}" y="{y + 13:.1f}">{f["properties"]["perches"]} P</text>')
    for name, ring in roads:
        pts = [to_lonlat(x, y) for x, y in ring]
        x, y = px(sum(p[0] for p in pts[:4]) / 4, sum(p[1] for p in pts[:4]) / 4)
        if name == "Main Road":
            parts.append(f'<text class="rn" x="{x:.1f}" y="{y + 5:.1f}">MAIN ROAD</text>')
    for tx, ty in [(-160, -88), (-140, -72), (-125, -90), (-150, -60), (-120, -66)]:
        x, y = px(*to_lonlat(tx, ty))
        parts.append(f'<circle cx="{x:.1f}" cy="{y:.1f}" r="11" fill="#5d9a45" stroke="#3d6b2c" stroke-width="1.5"/>')
    x, y = px(*to_lonlat(-142, -94))
    parts.append(f'<text class="pp" x="{x:.1f}" y="{y:.1f}">Playground</text>')
    parts.append("</svg>")
    (HERE / "data" / "site_plan.svg").write_text("\n".join(parts), encoding="utf-8")
    print(f"{len(feats)} plots; plan {wpx}x{hpx}px; bounds {site['bounds']}")


if __name__ == "__main__":
    main()
